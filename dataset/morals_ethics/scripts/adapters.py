# --------------------------------------------------------------------------- helpers
def clean(s):
    if s is None:
        return ""
    s = unicodedata.normalize("NFC", str(s))
    s = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", s)
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


def norm_key(s):
    s = unicodedata.normalize("NFKC", str(s)).lower()
    s = re.sub(r"[^a-z0-9]+", " ", s)
    return s.strip()


def rng_for(key):
    return random.Random(int(hashlib.sha1(key.encode()).hexdigest()[:12], 16))


def rec(**kw):
    base = dict(
        item_id="", source_dataset="", source_component="", source_item_id="", source_split="",
        origin="", task_type="", domain="", topic_tag="", ethical_framework="",
        scenario_text="", question_text="", response_format="", answer_options="",
        label="", label_raw="", label_type="none", label_transform="",
        label_distribution="", n_annotators="", label_agreement="",
        adversarial_filtered="", extra="",
        license="", citation="", source_url="", contamination_risk="",
        preserved_from_prior_workbook=False, _key="", _sim="", _lab="",
    )
    base.update(kw)
    for k in ("scenario_text", "question_text"):
        base[k] = clean(base[k])
    if isinstance(base["extra"], (dict, list)):
        base["extra"] = json.dumps(base["extra"], ensure_ascii=False, sort_keys=True)
    if isinstance(base["label_distribution"], (dict, list)):
        base["label_distribution"] = json.dumps(base["label_distribution"], ensure_ascii=False, sort_keys=True)
    return base


def read_csv_rows(path, **kw):
    with open(path, newline="", encoding="utf-8", errors="replace") as f:
        yield from csv.reader(f, **kw)


