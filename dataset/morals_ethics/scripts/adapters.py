    for i, ex in enumerate(t["examples"] if cfg.get("bigbench", {}).get("include_moral_permissibility") else []):
        ts = ex["target_scores"]
        txt = clean(ex["input"])
        if sum(ts.values()) != 1 or set(ts) != {"Yes", "No"}:
            yield {"_error": f"moral_permissibility {i}: unexpected target_scores {ts}"}
            continue
