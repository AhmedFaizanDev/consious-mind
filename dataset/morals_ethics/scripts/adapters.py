# --------------------------------------------------------------------------- MoralChoice
def moralchoice(cfg):
    base = RAW / "moralchoice" / "data" / "scenarios"
    for amb, fn in (("low", "moralchoice_low_ambiguity.csv"), ("high", "moralchoice_high_ambiguity.csv")):
        with open(base / fn, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                ctx, a1, a2 = clean(row["context"]), clean(row["action1"]), clean(row["action2"])
                if not (ctx and a1 and a2):
                    yield {"_error": f"moralchoice {row.get('scenario_id')}: missing fields"}
                    continue
                sid = row["scenario_id"]
                gen = row["generation_type"]
                flip = rng_for(sid).random() < 0.5
                x, y = (a2, a1) if flip else (a1, a2)
                if amb == "low":
                    # By dataset construction, action1 is the rule-compliant / preferred action.
                    label, ltype = ("B" if flip else "A"), "dataset_design_intended"
                    ltr = "MoralChoice low-ambiguity scenarios are constructed so that action1 is the morally preferred action (rule-compliant); options shuffled (seeded by id); label = position of action1. Authors' design intent, not an independent human verdict."
                else:
                    label, ltype, ltr = "", "none", "High-ambiguity scenario: no preferred action by design; no gold label."
                yield rec(
                    source_dataset="MoralChoice (Scherrer et al., 2023)", source_component=f"MoralChoice-{amb}-ambiguity",
                    source_item_id=sid, source_split="none",
                    origin="author_written" if gen == "Hand-Written" else "llm_generated_published",
                    task_type="two_action_choice", domain="harm_avoidance_rule_following" if amb == "low" else "value_conflict_dilemmas",
                    topic_tag=clean(row["generation_rule"]), ethical_framework="Rule-based (Gert's common morality)" ,
                    scenario_text=f"{ctx}\nAction A: {x}\nAction B: {y}",
                    question_text="Which action should you take?", response_format="binary_AB", answer_options="A|B",
                    label=label, label_raw="action1" if amb == "low" else "", label_type=ltype, label_transform=ltr,
                    extra={"ambiguity": amb, "generation_type": gen, "generation_rule": row["generation_rule"],
                           "rule_violation_labels_action1": {k[3:]: v for k, v in row.items() if k.startswith("a1_")},
                           "rule_violation_labels_action2": {k[3:]: v for k, v in row.items() if k.startswith("a2_")},
                           "note": "rule-violation labels (incl. 'No Agreement') are the source authors' crowd/auxiliary annotations; preserved verbatim; mapped to action1/action2 of the SOURCE order, not to A/B"},
                    license="MIT (moralchoice repository LICENSE.md; data in repo)",
                    citation="Scherrer, Shi, Feder & Blei 2023, 'Evaluating the Moral Beliefs Encoded in LLMs', NeurIPS (arXiv:2307.14324)",
                    source_url="https://github.com/ninodimontalcino/moralchoice",
                    contamination_risk="moderate-high (public since 2023)",
                    _key=norm_key(ctx + " || " + "||".join(sorted([a1, a2]))), _sim=f"{ctx} {a1} {a2}",
                )


