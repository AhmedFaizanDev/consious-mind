"""Source adapters: each yields normalized candidate records (dicts).

Rules for every adapter
  * never alter the original label; put it in `label_raw` and describe any mapping
    in `label_transform`
  * never invent annotator counts / agreement: those fields are filled only from
    numbers the source itself publishes, otherwise left empty
  * `origin` is one of
        human_authored            - written by people (crowd workers, Reddit users, researchers)
        llm_generated_published   - generated by an LLM by the *source dataset's authors* and
                                    published by them (not by this project)
        author_written            - hand written by the source dataset's authors/researchers
        synthetic_this_project    - generated by this project (see generate_synthetic.py)
  * `_key` is the natural-key text used for exact dedup; `_sim` the text used for
    near-duplicate clustering (both internal, dropped from the final CSV)
"""
